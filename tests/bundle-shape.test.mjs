import assert from "node:assert/strict";
import { readdir, readFile, stat } from "node:fs/promises";
import test from "node:test";

const rootUrl = new URL("../", import.meta.url);
const distUrl = new URL("dist/", rootUrl);

async function readDistFile(relativePath) {
  return readFile(new URL(relativePath, distUrl), "utf8");
}

test("generated bundle has the GitHub Pages-ready static shape", async () => {
  const [html, bundle, manifest] = await Promise.all([
    readDistFile("index.html"),
    readDistFile("assets/polyfly.js"),
    readDistFile("build-manifest.json"),
  ]);

  assert.match(html, /<script type="module" src="(?:\.\/|\/[^"/]+\/)assets\/polyfly\.js"><\/script>/);
  assert.doesNotMatch(html, /\.\/src\/main\.js/);
  assert.match(bundle, /^\/\/ Generated by scripts\/build\.mjs\. Do not edit dist\/ output\./);
  assert.match(bundle, /import \* as THREE from "https:\/\/cdn\.jsdelivr\.net\/npm\/three@0\.170\.0\/build\/three\.module\.js";/);
  assert.doesNotMatch(bundle, /"\.\/platform\/three\.js"/);

  const parsedManifest = JSON.parse(manifest);
  assert.equal(parsedManifest.sourceEntry, "src/main.js");
  assert.equal(parsedManifest.bundle, "assets/polyfly.js");
  assert.deepEqual(parsedManifest.externalModules, ["https://cdn.jsdelivr.net/npm/three@0.170.0/build/three.module.js"]);
});

test("dist contains only generated static-site files", async () => {
  const distEntries = await readdir(distUrl);
  assert.deepEqual(new Set(distEntries), new Set(["assets", "build-manifest.json", "index.html"]));

  const bundleStat = await stat(new URL("assets/polyfly.js", distUrl));
  assert.ok(bundleStat.size > 1_000, "bundle should contain the app entry, not an empty placeholder");
});
